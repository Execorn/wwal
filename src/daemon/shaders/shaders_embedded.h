static const char *SHADER_SRC_CROSSZOOM =
    "#version 310 es\n"
    "layout(local_size_x = 16, local_size_y = 16) in;\n"
    "\n"
    "layout(rgba8, binding = 0) writeonly uniform highp image2D u_target;\n"
    "layout(binding = 1) uniform highp sampler2D u_src_a;\n"
    "layout(binding = 2) uniform highp sampler2D u_src_b;\n"
    "\n"
    "uniform float u_progress;\n"
    "uniform ivec2 u_resolution;\n"
    "uniform vec2  u_center;\n"
    "uniform float u_wave_amp; /* Zoom intensity & blur strength */\n"
    "\n"
    "const float PI = 3.14159265359;\n"
    "\n"
    "vec4 sample_radial_blur(highp sampler2D tex, vec2 base_uv, vec2 step_vec) {\n"
    "    vec2 offset = step_vec * 0.25;\n"
    "    vec2 uv0 = clamp(base_uv - offset, 0.0, 1.0);\n"
    "    vec2 uv1 = clamp(base_uv + offset, 0.0, 1.0);\n"
    "    return (texture(tex, uv0) + texture(tex, uv1)) * 0.5;\n"
    "}\n"
    "\n"
    "void main() {\n"
    "    ivec2 coord = ivec2(gl_GlobalInvocationID.xy);\n"
    "    if (coord.x >= u_resolution.x || coord.y >= u_resolution.y) {\n"
    "        return;\n"
    "    }\n"
    "\n"
    "    vec2 uv = (vec2(coord) + 0.5) / vec2(u_resolution);\n"
    "    if (u_progress <= 0.0) {\n"
    "        imageStore(u_target, coord, texture(u_src_a, uv).bgra);\n"
    "        return;\n"
    "    }\n"
    "    if (u_progress >= 1.0) {\n"
    "        imageStore(u_target, coord, texture(u_src_b, uv).bgra);\n"
    "        return;\n"
    "    }\n"
    "\n"
    "    vec2 center = (u_center.x > 0.0 || u_center.y > 0.0) ? u_center : vec2(0.5);\n"
    "\n"
    "    float strength = (u_wave_amp > 0.001) ? u_wave_amp : 0.4;\n"
    "    float peak = sin(u_progress * PI);\n"
    "    float blur = peak * strength * 0.6;\n"
    "\n"
    "    float zoom_a = 1.0 - u_progress * strength;\n"
    "    float zoom_b = 1.0 + (1.0 - u_progress) * strength;\n"
    "    vec2 dir = uv - center;\n"
    "\n"
    "    vec2 base_a = clamp(center + dir * zoom_a, 0.0, 1.0);\n"
    "    vec2 base_b = clamp(center + dir * zoom_b, 0.0, 1.0);\n"
    "    vec2 step_vec = dir * blur;\n"
    "\n"
    "    vec4 color_a;\n"
    "    vec4 color_b;\n"
    "    if (blur < 0.001 || dot(step_vec, step_vec) < 1e-5) {\n"
    "        color_a = texture(u_src_a, base_a);\n"
    "        color_b = texture(u_src_b, base_b);\n"
    "    } else {\n"
    "        color_a = sample_radial_blur(u_src_a, base_a, step_vec);\n"
    "        color_b = sample_radial_blur(u_src_b, base_b, step_vec);\n"
    "    }\n"
    "\n"
    "    vec4 result = mix(color_a, color_b, u_progress);\n"
    "\n"
    "    /* Mid-transition exposure flare */\n"
    "    float flash = peak * 0.25;\n"
    "    result.rgb += vec3(flash);\n"
    "\n"
    "    imageStore(u_target, coord, clamp(result, 0.0, 1.0).bgra);\n"
    "}\n"
;

