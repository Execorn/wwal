static const char *SHADER_SRC_GROW =
    "#version 310 es\n"
    "layout(local_size_x = 16, local_size_y = 16) in;\n"
    "layout(rgba8, binding = 0) writeonly uniform highp image2D u_target;\n"
    "layout(binding = 1) uniform highp sampler2D u_src_a;\n"
    "layout(binding = 2) uniform highp sampler2D u_src_b;\n"
    "uniform float u_progress;\n"
    "uniform ivec2 u_resolution;\n"
    "uniform vec2 u_center;\n"
    "void main() {\n"
    "    ivec2 coord = ivec2(gl_GlobalInvocationID.xy);\n"
    "    if (coord.x >= u_resolution.x || coord.y >= u_resolution.y) return;\n"
    "    vec2 uv = (vec2(coord) + 0.5) / vec2(u_resolution);\n"
    "    float aspect = float(u_resolution.x) / float(u_resolution.y);\n"
    "    vec2 delta = uv - u_center;\n"
    "    delta.x *= aspect;\n"
    "    float dist = length(delta);\n"
    "    float max_dist = length(vec2(max(u_center.x, 1.0 - u_center.x) * aspect,\n"
    "                                 max(u_center.y, 1.0 - u_center.y)));\n"
    "    float r = u_progress * (max_dist + 0.05);\n"
    "    float edge = 0.03 * (max_dist + 0.05);\n"
    "    float alpha = smoothstep(dist - edge, dist + edge, r);\n"
    "    vec4 a = texture(u_src_a, uv);\n"
    "    vec4 b = texture(u_src_b, uv);\n"
    "    imageStore(u_target, coord, mix(a, b, alpha));\n"
    "}\n";

