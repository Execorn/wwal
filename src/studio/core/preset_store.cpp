PresetStore::PresetStore(QString baseDir, QObject *parent)
    : QObject(parent), m_baseDir(std::move(baseDir)) {
    ensureDirectoryExists();
}

QString PresetStore::sanitizeId(const QString &id) {
    if (id.isEmpty()) {
        return QStringLiteral("default");
    }

    QString sanitized = id;
    static const QRegularExpression unsafeChars(QStringLiteral("[^a-zA-Z0-9_.-]"));
    sanitized.replace(unsafeChars, QStringLiteral("_"));
    return sanitized;
}

QString PresetStore::presetDirectory() const {
    if (!m_baseDir.isEmpty()) {
        return m_baseDir;
    }

    char expanded[WAYWAL_PATH_MAX];
    if (waywal_expand_path("~/.config/waywal/presets", expanded, sizeof(expanded))) {
        return QString::fromUtf8(expanded);
    }

    const char *home = std::getenv("HOME");
    if (home && home[0] != '\0') {
        return QString::fromUtf8(home) + QStringLiteral("/.config/waywal/presets");
    }

    return QStringLiteral("/tmp/waywal/presets");
}

QString PresetStore::resolvePresetFilePath(const QString &id) const {
    QString safeId = sanitizeId(id);
    return QDir(presetDirectory()).filePath(safeId + QStringLiteral(".toml"));
}

void PresetStore::ensureDirectoryExists() const {
    QString dirPath = presetDirectory();
    QDir dir(dirPath);
    if (!dir.exists()) {
        dir.mkpath(QStringLiteral("."));
    }
}

bool PresetStore::hasPreset(const QString &id) const {
    return QFile::exists(resolvePresetFilePath(id));
}

QStringList PresetStore::listPresetIds() const {
    QDir dir(presetDirectory());
    if (!dir.exists()) {
        return {};
    }

    QStringList filters;
    filters << QStringLiteral("*.toml");
    QFileInfoList fileList = dir.entryInfoList(filters, QDir::Files, QDir::Name);

    QStringList ids;
    ids.reserve(fileList.size());
    for (const auto &info : fileList) {
        ids.append(info.completeBaseName());
    }
    return ids;
}

QList<WallpaperPreset> PresetStore::listAllPresets() const {
    QStringList ids = listPresetIds();
    QList<WallpaperPreset> presets;
    presets.reserve(ids.size());

    for (const auto &id : ids) {
        WallpaperPreset p{};
        if (const_cast<PresetStore *>(this)->loadPreset(id, p)) {
            presets.append(p);
        }
    }
    return presets;
}

bool PresetStore::deletePreset(const QString &id) {
    QString path = resolvePresetFilePath(id);
    if (!QFile::exists(path)) {
        return false;
    }

    if (QFile::remove(path)) {
        emit presetDeleted(id);
        return true;
    }

    emit errorOccurred(QStringLiteral("Failed to delete preset: ") + path);
    return false;
}

bool PresetStore::savePreset(const WallpaperPreset &preset) {
    ensureDirectoryExists();
    QString targetPath = resolvePresetFilePath(preset.id);

    QSaveFile file(targetPath);
    if (!file.open(QIODevice::WriteOnly | QIODevice::Text)) {
        emit errorOccurred(QStringLiteral("Failed to open preset file for writing: ") + targetPath);
        return false;
    }

    QTextStream out(&file);

    out << "# WayWal Wallpaper Preset\n";
    out << "# Automatically generated by wwal-studio\n\n";

    out << "[preset]\n";
    out << "id = \"" << sanitizeId(preset.id) << "\"\n";
    out << "title = \"" << preset.title << "\"\n";
    out << "wallpaper_path = \"" << preset.wallpaperPath << "\"\n\n";

    out << "[transition]\n";
    out << "type = \"" << preset.transitionType << "\"\n";
    out << "duration_ms = " << preset.transitionDurationMs << "\n";
    out << "fps = " << preset.transitionFps << "\n";
    out << "has_custom_bezier = " << (preset.hasCustomBezier ? "true" : "false") << "\n";
    out << "bezier = ["
        << QString::number(preset.bezier.p1x, 'f', 4) << ", "
        << QString::number(preset.bezier.p1y, 'f', 4) << ", "
        << QString::number(preset.bezier.p2x, 'f', 4) << ", "
        << QString::number(preset.bezier.p2y, 'f', 4) << "]\n\n";

    out << "[power]\n";
    out << "battery_policy = \"" << preset.batteryPolicy << "\"\n";
    out << "mute_on_audio = " << (preset.muteOnAudio ? "true" : "false") << "\n";
    out << "volume = " << QString::number(preset.volume, 'f', 3) << "\n\n";

    out << "[layout]\n";
    out << "crop_gravity_x = " << QString::number(preset.cropGravityX, 'f', 4) << "\n";
    out << "crop_gravity_y = " << QString::number(preset.cropGravityY, 'f', 4) << "\n";
    out << "has_crop_gravity = " << (preset.hasCropGravity ? "true" : "false") << "\n\n";

    if (!preset.uniforms.empty()) {
        out << "[uniforms]\n";
        for (const auto &[name, uval] : preset.uniforms) {
            switch (uval.type) {
            case UniformValue::Type::Float:
                out << name << " = " << QString::number(uval.floats[0], 'f', 6) << "\n";
                break;
            case UniformValue::Type::Int:
                out << name << " = " << uval.intVal << "\n";
                break;
            case UniformValue::Type::Bool:
                out << name << " = " << (uval.boolVal ? "true" : "false") << "\n";
                break;
            case UniformValue::Type::Vec2:
                out << name << " = ["
                    << QString::number(uval.floats[0], 'f', 6) << ", "
                    << QString::number(uval.floats[1], 'f', 6) << "]\n";
                break;
            case UniformValue::Type::Vec3:
                out << name << " = ["
                    << QString::number(uval.floats[0], 'f', 6) << ", "
                    << QString::number(uval.floats[1], 'f', 6) << ", "
                    << QString::number(uval.floats[2], 'f', 6) << "]\n";
                break;
            case UniformValue::Type::Vec4:
            case UniformValue::Type::Color:
                out << name << " = ["
                    << QString::number(uval.floats[0], 'f', 6) << ", "
                    << QString::number(uval.floats[1], 'f', 6) << ", "
                    << QString::number(uval.floats[2], 'f', 6) << ", "
                    << QString::number(uval.floats[3], 'f', 6) << "]\n";
                break;
            case UniformValue::Type::String:
                out << name << " = \"" << uval.stringVal << "\"\n";
                break;
            }
        }
        out << "\n";
    }

    if (!preset.extraProperties.empty()) {
        out << "[extra]\n";
        for (const auto &[key, val] : preset.extraProperties) {
            out << key << " = \"" << val << "\"\n";
        }
        out << "\n";
    }

    if (!file.commit()) {
        emit errorOccurred(QStringLiteral("Failed to commit preset file: ") + targetPath);
        return false;
    }

    emit presetSaved(preset.id);
    return true;
}

static std::vector<float> parseNumberArray(const QString &valStr) {
    std::vector<float> nums;
    QString trimmed = valStr.trimmed();
    if (trimmed.startsWith(QLatin1Char('[')) && trimmed.endsWith(QLatin1Char(']'))) {
        trimmed = trimmed.mid(1, trimmed.size() - 2);
    }
    const QStringList parts = trimmed.split(QLatin1Char(','), Qt::SkipEmptyParts);
    nums.reserve(parts.size());
    for (const auto &part : parts) {
        bool ok = false;
        float v = part.trimmed().toFloat(&ok);
        if (ok) {
            nums.push_back(v);
        }
    }
    return nums;
}

bool PresetStore::loadPreset(const QString &id, WallpaperPreset &outPreset) {
    QString path = resolvePresetFilePath(id);
    QFile file(path);
    if (!file.open(QIODevice::ReadOnly | QIODevice::Text)) {
        emit errorOccurred(QStringLiteral("Preset not found: ") + path);
        return false;
    }

    WallpaperPreset preset{};
    preset.id = sanitizeId(id);

    QTextStream in(&file);
    QString currentSection;

    while (!in.atEnd()) {
        QString line = in.readLine().trimmed();
        if (line.isEmpty() || line.startsWith(QLatin1Char('#'))) {
            continue;
        }

        if (line.startsWith(QLatin1Char('[')) && line.endsWith(QLatin1Char(']'))) {
            currentSection = line.mid(1, line.size() - 2).trimmed().toLower();
            continue;
        }

        int eqIdx = line.indexOf(QLatin1Char('='));
        if (eqIdx <= 0) {
            continue;
        }

        QString key = line.left(eqIdx).trimmed();
        QString val = line.mid(eqIdx + 1).trimmed();

        // Strip quotes if string
        QString unquoted = val;
        if ((unquoted.startsWith(QLatin1Char('"')) && unquoted.endsWith(QLatin1Char('"'))) ||
            (unquoted.startsWith(QLatin1Char('\'')) && unquoted.endsWith(QLatin1Char('\'')))) {
            unquoted = unquoted.mid(1, unquoted.size() - 2);
        }

        if (currentSection == QStringLiteral("preset")) {
            if (key == QStringLiteral("id")) {
                preset.id = unquoted;
            } else if (key == QStringLiteral("title")) {
                preset.title = unquoted;
            } else if (key == QStringLiteral("wallpaper_path")) {
                preset.wallpaperPath = unquoted;
            }
        } else if (currentSection == QStringLiteral("transition")) {
            if (key == QStringLiteral("type")) {
                preset.transitionType = unquoted;
            } else if (key == QStringLiteral("duration_ms")) {
                preset.transitionDurationMs = val.toUInt();
            } else if (key == QStringLiteral("fps")) {
                preset.transitionFps = val.toUInt();
            } else if (key == QStringLiteral("has_custom_bezier")) {
                preset.hasCustomBezier = (val.toLower() == QStringLiteral("true") || val == QStringLiteral("1"));
            } else if (key == QStringLiteral("bezier")) {
                std::vector<float> b = parseNumberArray(val);
                if (b.size() >= 4) {
                    preset.bezier = bezier_create(b[0], b[1], b[2], b[3]);
                    preset.hasCustomBezier = true;
                }
            }
        } else if (currentSection == QStringLiteral("power")) {
            if (key == QStringLiteral("battery_policy")) {
                preset.batteryPolicy = unquoted;
            } else if (key == QStringLiteral("mute_on_audio")) {
                preset.muteOnAudio = (val.toLower() == QStringLiteral("true") || val == QStringLiteral("1"));
            } else if (key == QStringLiteral("volume")) {
                preset.volume = val.toFloat();
            }
        } else if (currentSection == QStringLiteral("layout")) {
            if (key == QStringLiteral("crop_gravity_x")) {
                preset.cropGravityX = val.toFloat();
            } else if (key == QStringLiteral("crop_gravity_y")) {
                preset.cropGravityY = val.toFloat();
            } else if (key == QStringLiteral("has_crop_gravity")) {
                preset.hasCropGravity = (val.toLower() == QStringLiteral("true") || val == QStringLiteral("1"));
            }
        } else if (currentSection == QStringLiteral("uniforms")) {
            if (val.startsWith(QLatin1Char('['))) {
                std::vector<float> nums = parseNumberArray(val);
                if (nums.size() == 1) {
                    preset.uniforms[key] = UniformValue::fromFloat(nums[0]);
                } else if (nums.size() == 2) {
                    preset.uniforms[key] = UniformValue::fromVec2(nums[0], nums[1]);
                } else if (nums.size() == 3) {
                    preset.uniforms[key] = UniformValue::fromVec3(nums[0], nums[1], nums[2]);
                } else if (nums.size() >= 4) {
                    preset.uniforms[key] = UniformValue::fromVec4(nums[0], nums[1], nums[2], nums[3]);
                }
            } else if (val.toLower() == QStringLiteral("true") || val.toLower() == QStringLiteral("false")) {
                preset.uniforms[key] = UniformValue::fromBool(val.toLower() == QStringLiteral("true"));
            } else if (val.startsWith(QLatin1Char('"')) || val.startsWith(QLatin1Char('\''))) {
                preset.uniforms[key] = UniformValue::fromString(unquoted);
            } else if (val.contains(QLatin1Char('.')) || val.contains(QLatin1Char('e')) || val.contains(QLatin1Char('E'))) {
                preset.uniforms[key] = UniformValue::fromFloat(val.toFloat());
            } else {
                bool isInt = false;
                int intVal = val.toInt(&isInt);
                if (isInt) {
                    preset.uniforms[key] = UniformValue::fromInt(intVal);
                } else {
                    preset.uniforms[key] = UniformValue::fromString(val);
                }
            }
        } else if (currentSection == QStringLiteral("extra")) {
            preset.extraProperties[key] = unquoted;
        }
    }

    outPreset = std::move(preset);
    return true;
}

